/* Generate public Vue exports from every .ce.vue under src/components/.
 * 组件按文档分组放进子目录；文件名仍是公开 API 边界，子目录只组织源码。
 * Called by vite.config.js for dev and build: await generateExports().
 * Example: components/core/text-field.ce.vue becomes the named export KimaTextField.
 * To add a component: drop a new .ce.vue file into the right src/components/ subfolder.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";

/** Recursively collect .ce.vue files, keeping their path relative to src/components/. */
async function collect(folder, prefix = "") {
  const files = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      files.push(...await collect(new URL(`${entry.name}/`, folder), `${prefix}${entry.name}/`));
      continue;
    }
    if (entry.name.endsWith(".ce.vue")) files.push({ name: entry.name, relative: `${prefix}${entry.name}` });
  }
  return files;
}

/** Write src/index.js from component filenames, preserving real named exports. */
export async function generateExports() {
  const folder = new URL("../src/components/", import.meta.url);
  const components = [];
  for (const { name: file, relative } of await collect(folder)) {
    const name = file.slice(0, -".ce.vue".length);
    // Filenames are the public API boundary: invalid or duplicate names cannot ship.
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) {
      throw new Error(`Invalid KIMA component filename: ${relative}`);
    }
    const exportName = `Kima${name.split("-").map((word) => word[0].toUpperCase() + word.slice(1)).join("")}`;
    if (components.some((component) => component.exportName === exportName)) {
      throw new Error(`Duplicate KIMA component export: ${exportName}`);
    }
    components.push({ exportName, slug: name, relative, path: `./components/${relative}` });
  }
  // Match ES module namespace key order (code-point order, not locale collation).
  components.sort((a, b) => a.exportName < b.exportName ? -1 : a.exportName > b.exportName ? 1 : 0);
  const content = [
    "/* Generated by scripts/components.js when Vite loads; do not edit this list.",
    " * Add/remove .ce.vue files under src/components/<group> instead. Vue usage:",
    ' * import { KimaButton, componentNames } from "@kernel4632/kima";',
    ' * import "@kernel4632/kima/style.css";',
    " */",
    'import "./styles/_tokens.scss";',
    "",
    ...components.map(({ exportName, path }) => `export { default as ${exportName} } from ${JSON.stringify(path)};`),
    "",
    `export const componentNames = ${JSON.stringify(components.map(({ exportName }) => exportName), null, 2)};`,
    "",
  ].join("\n");
  const entry = new URL("../src/index.js", import.meta.url);
  // Avoid unnecessary source changes and dev reloads when the component set is unchanged.
  if (await readFile(entry, "utf8") !== content) await writeFile(entry, content);

  // Tests and tooling load one component by slug; keep the mapping next to the source
  // so a file move never needs a second hand-maintained path list.
  const paths = Object.fromEntries(components.map(({ slug, relative }) => [slug, `/src/components/${relative}`]));
  const pathContent = [
    "/* Generated by scripts/components.js; do not edit.",
    " * Public slug to grouped source path, for tests and tooling.",
    " */",
    `export const componentPaths = ${JSON.stringify(paths, null, 2)};`,
    "",
  ].join("\n");
  const pathEntry = new URL("../src/component-paths.js", import.meta.url);
  if (await readFile(pathEntry, "utf8").catch(() => "") !== pathContent) await writeFile(pathEntry, pathContent);
}
